def parse_date(s):
    s = (s or '').strip()
    if not s: return None
    m = re.match(r'^(\d{4})-(\d{2})(?:-(\d{2}))?$', s)
    if not m: return None
    y, mo, d = int(m.group(1)), int(m.group(2)), int(m.group(3) or 15)
    try: return date(y, mo, d)
    except ValueError: return None

def months(exam, base):
    a, b = parse_date(exam), parse_date(base)
    if not a or not b: return ''
    return round((a - b).days / 30.4375, 1)

def main():
    old_path, uniq_path, out_path = sys.argv[1:4]
    old = [json.loads(l) for l in open(old_path, encoding='utf8') if l.strip()]
    uniq = [json.loads(l) for l in open(uniq_path, encoding='utf8') if l.strip()]
    # 旧编号 -> 本轮去重编号（题干前40字 + 出现省份消歧）
    bykey = {}
    for u in uniq:
        bykey.setdefault((str(u['year']), u['module'], norm(u['stem'])[:40]), []).append(u)
    uidx0 = {u['uid']: u for u in uniq}
    remap = {}
    for r in old:
        # 已经用本轮编号的（重跑时）直接保留
        if r['编号'] in uidx0 and norm(uidx0[r['编号']]['stem']).startswith(norm(r['题干前60字'])[:40]):
            remap[r['编号']] = r['编号']
            continue
        cands = bykey.get((str(r['年度']), r['模块'], norm(r['题干前60字'])[:40]), [])
        if len(cands) == 1:
            remap[r['编号']] = cands[0]['uid']
        else:
            pick = [u for u in cands if u['appear'][0]['region'] in r['出现省份']]
            assert len(pick) == 1, (r['编号'], len(cands), len(pick))
            remap[r['编号']] = pick[0]['uid']
    rows = []
    for r in old:
        r = dict(r)
        r['编号'] = remap[r['编号']]
        r.update(FIX.get(r['编号'], {}))
        if r['编号'] in URL:
            r['依据URL'] = URL[r['编号']]
        else:
            r.pop('依据URL', None)
        rows.append(r)
    have = {r['编号'] for r in rows}
    for n in NEW:
        if n['编号'] not in have:
            rows.append(dict(n))
    # 解析出处（便于抽查：仓库文件 + 题号）
    uidx = {u['uid']: u for u in uniq}
    for r in rows:
        u = uidx.get(r['编号'])
        if u:
            a = u['appear'][0]
            r['解析来源'] = f"ERRRC/xingcezhenti {'01-政治理论' if u['module']=='政治理论' else '02-常识判断'}/{a['paper'].replace('/','-')}.md 第{a['no']}题" 
    for r in rows:
        src = EXAM_SRC.get((str(r['年度']), r['考试']))
        if src:
            r['笔试日期'], r['笔试日期来源'] = src.split('。', 1)
        r['距笔试月数'] = months(r['笔试日期'], r['依据发布日期'])
        if not r['距笔试月数']:
            r['距笔试月数'] = ''
    order = ['编号','年度','考试','卷别','出现省份','笔试日期','笔试日期来源','模块','题干前60字','题型',
             '依据名称','依据类型','依据发布日期','依据URL','距笔试月数','专题','备注','解析来源']
    rows.sort(key=lambda r: r['编号'])
    with open(out_path, 'w', encoding='utf8') as w:
        for r in rows:
            out = {k: r.get(k, '') for k in order if k in r or k != '依据URL'}
            w.write(json.dumps(out, ensure_ascii=False) + '\n')
    print('rows', len(rows))

main()
